-- ---------- 4.1 PKG_SG_NOMINA: calculos de nomina de un emprendimiento ----------
CREATE OR REPLACE PACKAGE pkg_sg_nomina AS
  FUNCTION trabajadores_activos(p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  FUNCTION nomina_mensual   (p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  FUNCTION nomina_quincenal (p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  FUNCTION total_deducciones(p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  FUNCTION nomina_neta      (p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  PROCEDURE listar_nomina   (p_emprendimiento_id IN NUMBER);
END pkg_sg_nomina;
/

CREATE OR REPLACE PACKAGE BODY pkg_sg_nomina AS

  FUNCTION trabajadores_activos (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
    v_total NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO v_total
      FROM sg_trabajador
     WHERE emprendimiento_id = p_emprendimiento_id
       AND estado = 'activo';
    RETURN v_total;
  END trabajadores_activos;

  -- Suma de los salarios base de los trabajadores activos
  FUNCTION nomina_mensual (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
    v_total NUMBER;
  BEGIN
    SELECT NVL(SUM(c.salario_base), 0)
      INTO v_total
      FROM sg_trabajador t
      JOIN sg_cargo c ON c.id = t.cargo_id
     WHERE t.emprendimiento_id = p_emprendimiento_id
       AND t.estado = 'activo';
    RETURN v_total;
  END nomina_mensual;

  FUNCTION nomina_quincenal (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
  BEGIN
    RETURN nomina_mensual(p_emprendimiento_id) / 2;
  END nomina_quincenal;

  FUNCTION total_deducciones (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
  BEGIN
    RETURN fn_sg_deducciones(nomina_mensual(p_emprendimiento_id));
  END total_deducciones;

  FUNCTION nomina_neta (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
  BEGIN
    RETURN fn_sg_salario_neto(nomina_mensual(p_emprendimiento_id));
  END nomina_neta;

  PROCEDURE listar_nomina (p_emprendimiento_id IN NUMBER) IS
    v_hay BOOLEAN := FALSE;
  BEGIN
    FOR r IN (SELECT t.nombre, t.apellido, c.nombre AS cargo, c.salario_base
                FROM sg_trabajador t
                JOIN sg_cargo c ON c.id = t.cargo_id
               WHERE t.emprendimiento_id = p_emprendimiento_id
                 AND t.estado = 'activo'
               ORDER BY t.nombre) LOOP
      v_hay := TRUE;
      DBMS_OUTPUT.PUT_LINE(r.nombre || ' ' || r.apellido || ' (' || r.cargo || ')'
                           || ' | salario: ' || r.salario_base
                           || ' | deducciones: ' || fn_sg_deducciones(r.salario_base)
                           || ' | neto: ' || fn_sg_salario_neto(r.salario_base));
    END LOOP;

    IF NOT v_hay THEN
      DBMS_OUTPUT.PUT_LINE('No hay trabajadores activos');
    END IF;
    DBMS_OUTPUT.PUT_LINE('Nomina mensual: ' || nomina_mensual(p_emprendimiento_id)
                         || ' | neta: ' || nomina_neta(p_emprendimiento_id));
  END listar_nomina;

END pkg_sg_nomina;
/

-- ---------- 4.2 PKG_SG_REPORTES: indicadores de ventas y finanzas ----------
CREATE OR REPLACE PACKAGE pkg_sg_reportes AS
  FUNCTION total_ventas (p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  FUNCTION total_ventas_rango (p_emprendimiento_id IN NUMBER, p_desde IN DATE, p_hasta IN DATE) RETURN NUMBER;
  FUNCTION total_ingresos (p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  FUNCTION total_gastos (p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  FUNCTION utilidad (p_emprendimiento_id IN NUMBER) RETURN NUMBER;
  PROCEDURE top_productos (p_emprendimiento_id IN NUMBER, p_limite IN NUMBER);
  PROCEDURE reporte (p_emprendimiento_id IN NUMBER);
END pkg_sg_reportes;
/

CREATE OR REPLACE PACKAGE BODY pkg_sg_reportes AS

  FUNCTION total_ventas (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
  BEGIN
    RETURN total_ventas_rango(p_emprendimiento_id, DATE '1900-01-01', DATE '9999-12-31');
  END total_ventas;

  FUNCTION total_ventas_rango (p_emprendimiento_id IN NUMBER, p_desde IN DATE, p_hasta IN DATE) RETURN NUMBER IS
    v_total NUMBER;
  BEGIN
    SELECT NVL(SUM(d.cantidad * d.precio_unitario), 0)
      INTO v_total
      FROM sg_detalle_venta d
      JOIN sg_venta v ON v.id = d.venta_id
     WHERE v.emprendimiento_id = p_emprendimiento_id
       AND TRUNC(v.fecha) BETWEEN TRUNC(p_desde) AND TRUNC(p_hasta);
    RETURN v_total;
  END total_ventas_rango;

  -- Ingresos = movimientos de tipo Venta o Ingreso (igual que Movimiento.EsIngreso en C#)
  FUNCTION total_ingresos (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
    v_total NUMBER;
  BEGIN
    SELECT NVL(SUM(monto), 0)
      INTO v_total
      FROM sg_movimiento
     WHERE emprendimiento_id = p_emprendimiento_id
       AND tipo IN ('Venta', 'Ingreso');
    RETURN v_total;
  END total_ingresos;

  -- Gastos = movimientos de tipo Compra o Gasto (igual que Movimiento.EsGasto en C#)
  FUNCTION total_gastos (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
    v_total NUMBER;
  BEGIN
    SELECT NVL(SUM(monto), 0)
      INTO v_total
      FROM sg_movimiento
     WHERE emprendimiento_id = p_emprendimiento_id
       AND tipo IN ('Compra', 'Gasto');
    RETURN v_total;
  END total_gastos;

  -- Utilidad = balance de Finanzas (ingresos - gastos)
  FUNCTION utilidad (p_emprendimiento_id IN NUMBER) RETURN NUMBER IS
  BEGIN
    RETURN fn_sg_balance(p_emprendimiento_id);
  END utilidad;

  PROCEDURE top_productos (p_emprendimiento_id IN NUMBER, p_limite IN NUMBER) IS
  BEGIN
    DBMS_OUTPUT.PUT_LINE('--- Productos mas vendidos ---');
    FOR r IN (SELECT * FROM (
                SELECT d.producto_nombre AS nombre,
                       SUM(d.cantidad) AS unidades,
                       SUM(d.cantidad * d.precio_unitario) AS ingresos
                  FROM sg_detalle_venta d
                  JOIN sg_venta v ON v.id = d.venta_id
                 WHERE v.emprendimiento_id = p_emprendimiento_id
                 GROUP BY d.producto_nombre
                 ORDER BY unidades DESC)
               WHERE ROWNUM <= p_limite) LOOP
      DBMS_OUTPUT.PUT_LINE(r.nombre || ' | unidades: ' || r.unidades || ' | ingresos: ' || r.ingresos);
    END LOOP;
  END top_productos;

  PROCEDURE reporte (p_emprendimiento_id IN NUMBER) IS
  BEGIN
    DBMS_OUTPUT.PUT_LINE('Total ventas : ' || total_ventas(p_emprendimiento_id));
    DBMS_OUTPUT.PUT_LINE('Total gastos : ' || total_gastos(p_emprendimiento_id));
    DBMS_OUTPUT.PUT_LINE('Utilidad     : ' || utilidad(p_emprendimiento_id));
    top_productos(p_emprendimiento_id, 3);
  END reporte;

END pkg_sg_reportes;
/

