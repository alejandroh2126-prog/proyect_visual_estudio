-- Resumen general de un emprendimiento
CREATE OR REPLACE PROCEDURE sp_sg_resumen_emprendimiento (
  p_emprendimiento_id IN NUMBER
) IS
  v_nombre       sg_emprendimiento.nombre%TYPE;
  v_productos    NUMBER;
  v_trabajadores NUMBER;
  v_ventas       NUMBER;
BEGIN
  SELECT nombre
    INTO v_nombre
    FROM sg_emprendimiento
   WHERE id = p_emprendimiento_id;

  SELECT COUNT(*) INTO v_productos
    FROM sg_producto
   WHERE emprendimiento_id = p_emprendimiento_id;

  SELECT COUNT(*) INTO v_trabajadores
    FROM sg_trabajador
   WHERE emprendimiento_id = p_emprendimiento_id
     AND estado = 'activo';

  SELECT COUNT(*) INTO v_ventas
    FROM sg_venta
   WHERE emprendimiento_id = p_emprendimiento_id;

  DBMS_OUTPUT.PUT_LINE('===== ' || v_nombre || ' =====');
  DBMS_OUTPUT.PUT_LINE('Productos        : ' || v_productos);
  DBMS_OUTPUT.PUT_LINE('Trabajadores     : ' || v_trabajadores);
  DBMS_OUTPUT.PUT_LINE('Ventas realizadas: ' || v_ventas);
  DBMS_OUTPUT.PUT_LINE('Balance          : ' || TO_CHAR(fn_sg_balance(p_emprendimiento_id), 'FM999,999,999,990.00'));
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'El emprendimiento ' || p_emprendimiento_id || ' no existe');
END sp_sg_resumen_emprendimiento;
/

-- Lista los productos con stock en o por debajo del minimo (igual que la alerta de Inventario)
CREATE OR REPLACE PROCEDURE sp_sg_productos_stock_bajo (
  p_emprendimiento_id IN NUMBER
) IS
  v_hay BOOLEAN := FALSE;
BEGIN
  FOR r IN (SELECT nombre, stock, stock_minimo
              FROM sg_producto
             WHERE emprendimiento_id = p_emprendimiento_id
               AND stock <= stock_minimo
             ORDER BY stock) LOOP
    v_hay := TRUE;
    DBMS_OUTPUT.PUT_LINE('ALERTA: ' || r.nombre || ' - stock ' || r.stock || ' (minimo ' || r.stock_minimo || ')');
  END LOOP;

  IF NOT v_hay THEN
    DBMS_OUTPUT.PUT_LINE('Ningun producto con stock bajo');
  END IF;
END sp_sg_productos_stock_bajo;
/

-- Sube o baja el precio de venta de TODOS los productos de un emprendimiento en un porcentaje.
-- El disparador trg_sg_producto_precio_aud deja registrado cada cambio.
-- No hace COMMIT: quien la llama decide si confirma o deshace.
CREATE OR REPLACE PROCEDURE sp_sg_ajustar_precio_venta (
  p_emprendimiento_id IN NUMBER,
  p_porcentaje        IN NUMBER
) IS
BEGIN
  IF p_porcentaje IS NULL OR p_porcentaje <= -100 THEN
    RAISE_APPLICATION_ERROR(-20002, 'El porcentaje debe ser mayor que -100');
  END IF;

  UPDATE sg_producto
     SET precio_venta = ROUND(precio_venta * (1 + p_porcentaje / 100), 2)
   WHERE emprendimiento_id = p_emprendimiento_id;

  DBMS_OUTPUT.PUT_LINE('Productos actualizados: ' || SQL%ROWCOUNT);
END sp_sg_ajustar_precio_venta;
/

-- Estado de los presupuestos de un mes: OK, ALERTA (>= 80 %) o EXCEDIDO (igual que la pantalla de Presupuestos)
CREATE OR REPLACE PROCEDURE sp_sg_presupuestos_estado (
  p_emprendimiento_id IN NUMBER,
  p_mes               IN VARCHAR2
) IS
  v_estado VARCHAR2(10);
  v_hay    BOOLEAN := FALSE;
BEGIN
  FOR r IN (SELECT p.categoria,
                   p.monto_limite,
                   NVL((SELECT SUM(m.monto)
                          FROM sg_movimiento m
                         WHERE m.emprendimiento_id = p.emprendimiento_id
                           AND m.tipo IN ('Compra', 'Gasto')
                           AND m.categoria = p.categoria
                           AND TO_CHAR(m.fecha, 'YYYY-MM') = p.mes), 0) AS gastado
              FROM sg_presupuesto p
             WHERE p.emprendimiento_id = p_emprendimiento_id
               AND p.mes = p_mes
             ORDER BY p.categoria) LOOP
    v_hay := TRUE;

    IF r.gastado > r.monto_limite THEN
      v_estado := 'EXCEDIDO';
    ELSIF r.monto_limite > 0 AND r.gastado / r.monto_limite * 100 >= 80 THEN
      v_estado := 'ALERTA';
    ELSE
      v_estado := 'OK';
    END IF;

    DBMS_OUTPUT.PUT_LINE(RPAD(r.categoria, 20) || ' gastado ' || r.gastado || ' de ' || r.monto_limite || '  -> ' || v_estado);
  END LOOP;

  IF NOT v_hay THEN
    DBMS_OUTPUT.PUT_LINE('No hay presupuestos para ese mes');
  END IF;
END sp_sg_presupuestos_estado;
/

-- Borra de la bitacora los registros con mas de p_dias dias de antiguedad
CREATE OR REPLACE PROCEDURE sp_sg_limpiar_bitacora (
  p_dias IN NUMBER
) IS
BEGIN
  IF p_dias IS NULL OR p_dias < 0 THEN
    RAISE_APPLICATION_ERROR(-20003, 'Los dias deben ser cero o mas');
  END IF;

  DELETE FROM sg_bitacora
   WHERE fecha < SYSDATE - p_dias;

  DBMS_OUTPUT.PUT_LINE('Registros eliminados de la bitacora: ' || SQL%ROWCOUNT);
END sp_sg_limpiar_bitacora;
/

