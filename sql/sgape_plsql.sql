/* =====================================================================
   SGAPE - Sistema de Gestion y Administracion de Emprendimientos
   Parte PL/SQL de la base de datos Oracle: funciones, procedimientos,
   paquetes y disparadores sobre las tablas SG_* que usa el programa.

   COMO EJECUTARLO:
     1. Primero ejecuta sgape_oracle.sql (crea las tablas SG_*).
     2. Luego ejecuta ESTE archivo completo con "Ejecutar script" (F5).
        Se puede repetir las veces que quieras (todo es CREATE OR REPLACE).
     3. Al final del archivo van las pruebas (seccion 6). Las pruebas se deshacen
        con ROLLBACK: no dejan datos en tus tablas.

   QUE USA EL PROGRAMA (C#) DE ESTE ARCHIVO:
     - pkg_sg_nomina.*          -> resumen de nomina (pantallas Nomina e Inicio)
     - pkg_sg_reportes.total_*  -> totales de ingresos y gastos (Finanzas, Inicio, Reportes)
     - sp_sg_limpiar_bitacora   -> se ejecuta al abrir el programa (borra bitacora de mas de 1 año)
     - los 5 disparadores       -> se activan solos cuando el programa guarda datos
     (Las demas funciones y procedimientos las usan los paquetes o se llaman desde SQL.)

   IMPORTANTE: las reglas de negocio (stock, descuento de inventario,
   ingresos de ventas) siguen viviendo en C#. Aqui NO se repiten: las
   funciones y paquetes solo LEEN datos para calcular, y los disparadores
   solo AUDITAN o VALIDAN. Asi el programa y la base nunca se contradicen.

   Orden: 1 tablas de apoyo | 2 funciones | 3 procedimientos |
          4 paquetes | 5 disparadores | 6 pruebas
   ===================================================================== */

SET SERVEROUTPUT ON;

