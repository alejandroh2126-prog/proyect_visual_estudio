-- ---------- prueba (se deshace) ----------
DECLARE
  v_usuario NUMBER; v_emp NUMBER; v_mov NUMBER; v_obl NUMBER; v_pago NUMBER;
  v_estado VARCHAR2(10); v_monto NUMBER; v_bal NUMBER; v_aporte NUMBER; v_inversion NUMBER;
BEGIN
  SELECT id INTO v_aporte    FROM sg_categoria_movimiento WHERE nombre = 'Aportes de socios' AND tipo = 'Ingreso';
  SELECT id INTO v_inversion FROM sg_categoria_movimiento WHERE nombre = 'Inversión' AND tipo = 'Ingreso';
  SAVEPOINT prueba_aportes;
  INSERT INTO sg_usuario (nombre, email, clave_hash) VALUES ('Prueba aportes', 'prueba.aportes@sgape.co', 'x:y')
  RETURNING id INTO v_usuario;
  INSERT INTO sg_emprendimiento (usuario_id, nombre, sector_id, ciudad_codigo, fecha_inicio)
  VALUES (v_usuario, 'Prueba aportes', (SELECT MIN(id) FROM sg_sector), '20001', SYSDATE - 10)
  RETURNING id INTO v_emp;

  -- 1.000.000 de un socio, devolver 30 %: pendiente
  sp_sg_registrar_aporte(v_emp, v_aporte, NULL, 1000000, SYSDATE, 'Socio prueba', 30, 'N', v_mov, v_obl);
  SELECT estado, monto INTO v_estado, v_monto FROM sg_obligacion_socio WHERE id = v_obl;
  IF v_estado = 'pendiente' AND v_monto = 300000 THEN DBMS_OUTPUT.PUT_LINE('OK    aporte con 30 % pendiente');
  ELSE DBMS_OUTPUT.PUT_LINE('FALLA aporte pendiente: ' || v_estado || ' ' || v_monto); END IF;

  sp_sg_pagar_obligacion(v_emp, v_obl, SYSDATE, v_pago);
  v_bal := fn_sg_balance(v_emp);
  IF v_bal = 700000 THEN DBMS_OUTPUT.PUT_LINE('OK    devolucion pagada: balance 700.000');
  ELSE DBMS_OUTPUT.PUT_LINE('FALLA balance ' || v_bal); END IF;

  -- inversion de 500.000 con 110 %: gasto inmediato
  sp_sg_registrar_aporte(v_emp, v_inversion, 'Capital semilla', 500000, SYSDATE, 'Inversionista', 110, 'S', v_mov, v_obl);
  SELECT estado INTO v_estado FROM sg_obligacion_socio WHERE id = v_obl;
  v_bal := fn_sg_balance(v_emp);
  IF v_estado = 'pagada' AND v_bal = 650000 THEN DBMS_OUTPUT.PUT_LINE('OK    inversion con gasto inmediato');
  ELSE DBMS_OUTPUT.PUT_LINE('FALLA gasto inmediato: ' || v_estado || ' ' || v_bal); END IF;

  BEGIN
    sp_sg_pagar_obligacion(v_emp, v_obl, SYSDATE, v_pago);
    DBMS_OUTPUT.PUT_LINE('FALLA pago doble permitido');
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE = -20145 THEN DBMS_OUTPUT.PUT_LINE('OK    no se paga dos veces'); ELSE RAISE; END IF;
  END;
  ROLLBACK TO prueba_aportes;
  DBMS_OUTPUT.PUT_LINE('Prueba terminada (datos deshechos).');
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK TO prueba_aportes;
    DBMS_OUTPUT.PUT_LINE('ERROR EN LA PRUEBA: ' || SQLERRM);
END;
/

