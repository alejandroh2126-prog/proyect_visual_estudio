   devolverle al socio o inversionista. La devolucion:
     - queda PENDIENTE (Finanzas > Por devolver) hasta que se paga, o
     - se registra enseguida como GASTO ("Devolución a socios").

   Crea / cambia:
     categorias 'Inversión' (ingreso) y 'Devolución a socios' (gasto de sistema)
     sg_obligacion_socio          lo que se le debe devolver a cada socio
     vw_sg_obligaciones_socio     con la fecha y la categoria del aporte
