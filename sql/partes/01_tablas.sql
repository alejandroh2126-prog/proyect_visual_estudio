CREATE INDEX ix_sg_ciudad_depto   ON sg_ciudad (departamento_codigo);
CREATE INDEX ix_sg_emp_usuario    ON sg_emprendimiento (usuario_id);
CREATE INDEX ix_sg_emp_sector     ON sg_emprendimiento (sector_id);
CREATE INDEX ix_sg_emp_ciudad     ON sg_emprendimiento (ciudad_codigo);
CREATE INDEX ix_sg_cargo_plant    ON sg_cargo (plantilla_id);
CREATE INDEX ix_sg_trab_cargo     ON sg_trabajador (cargo_id);
CREATE INDEX ix_sg_trab_tdoc      ON sg_trabajador (tipo_documento);
CREATE INDEX ix_sg_trab_ciudad    ON sg_trabajador (ciudad_codigo);
CREATE INDEX ix_sg_venta_emp      ON sg_venta (emprendimiento_id, fecha);
CREATE INDEX ix_sg_det_venta      ON sg_detalle_venta (venta_id);
CREATE INDEX ix_sg_mov_emp        ON sg_movimiento (emprendimiento_id, fecha);
CREATE INDEX ix_sg_mov_cat        ON sg_movimiento (categoria_id);
CREATE INDEX ix_sg_pres_cat       ON sg_presupuesto (categoria_id);
CREATE INDEX ix_sg_vac_emp        ON sg_vacante (emprendimiento_id);
CREATE INDEX ix_sg_vac_cargo      ON sg_vacante (cargo_id);
CREATE INDEX ix_sg_vac_ciudad     ON sg_vacante (ciudad_codigo);
CREATE INDEX ix_sg_post_vacante   ON sg_postulacion (vacante_id);
CREATE INDEX ix_sg_post_ciudad    ON sg_postulacion (ciudad_codigo);
CREATE INDEX ix_sg_tvin_usuario   ON sg_telegram_vinculo (usuario_id);
CREATE INDEX ix_sg_tvin_emp       ON sg_telegram_vinculo (emprendimiento_id);
CREATE INDEX ix_sg_tcod_usuario   ON sg_telegram_codigo (usuario_id);
-- Las UNIQUE (emprendimiento_id, ...) ya crean un indice que empieza por emprendimiento_id,
-- por eso cargo, trabajador, producto y presupuesto no necesitan otro indice para esa llave.
