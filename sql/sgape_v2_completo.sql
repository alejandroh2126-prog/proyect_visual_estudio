    precio_compra_nuevo  NUMBER(14,2),
    precio_venta_ant     NUMBER(14,2),
    precio_venta_nuevo   NUMBER(14,2),
    usuario_bd           VARCHAR2(60),
    fecha                DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_sg_auditoria_precio PRIMARY KEY (id)
);

CREATE TABLE sg_bitacora (
    id           NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tabla        VARCHAR2(30)  NOT NULL,
    operacion    VARCHAR2(10)  NOT NULL,
    registro_id  NUMBER(10),
    detalle      VARCHAR2(200),
    usuario_bd   VARCHAR2(60),
    fecha        DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_sg_bitacora PRIMARY KEY (id)
);

-- Preguntas frecuentes que el bot usa como contexto para responder dudas de uso
CREATE TABLE sg_conocimiento (
    id         NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
