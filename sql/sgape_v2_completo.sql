    END IF;
  ELSE
    INSERT INTO sg_bitacora (tabla, operacion, registro_id, detalle, usuario_bd)
    VALUES ('SG_EMPRENDIMIENTO', 'DELETE', :OLD.id, SUBSTR('Emprendimiento eliminado: ' || :OLD.nombre, 1, 200), USER);
  END IF;
